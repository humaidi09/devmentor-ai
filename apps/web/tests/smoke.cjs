const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH || undefined,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const health=await context.request.get('http://localhost:8000/health').then(r=>r.json());
 assert.equal(health.demo_mode,true,'Smoke tests require an isolated demo API');
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/chat',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:/Understand a concept/}).click();
 await page.getByText('Demo response',{exact:true}).waitFor();
 const url=page.url();assert.match(url,/conversation=/);
 await page.reload({waitUntil:'networkidle'});
 await page.getByText('Demo response',{exact:true}).waitFor();
 await page.getByRole('button',{name:'New chat',exact:true}).click();
 await page.getByRole('heading',{name:'What are we learning today?'}).waitFor();
 await page.getByLabel('Conversation history').selectOption({index:1});
 await page.getByText('Demo response',{exact:true}).waitFor();
 await page.goto('http://localhost:3000/dashboard',{waitUntil:'networkidle'});
 await page.getByText('Current streak',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Generate plan',exact:true}).click();
 await page.getByText("Today's plan generated.",{exact:true}).waitFor();
 const before=await page.request.get('http://localhost:8000/api/tasks?limit=100').then(r=>r.json());
 await page.getByRole('button',{name:'Generate plan',exact:true}).click();
 await page.getByRole('button',{name:'Generate plan',exact:true}).waitFor({state:'visible'});
 const after=await page.request.get('http://localhost:8000/api/tasks?limit=100').then(r=>r.json());assert.equal(before.count,after.count);
 await page.getByRole('button',{name:'Start focus',exact:true}).click();
 const focus=page.getByRole('dialog',{name:'Focus timer'});
 await focus.getByRole('button',{name:'Start',exact:true}).click();
 await focus.getByRole('button',{name:'Pause',exact:true}).waitFor();
 await focus.getByRole('button',{name:'Pause',exact:true}).click();
 await focus.getByRole('button',{name:'Start',exact:true}).waitFor();
 await focus.getByRole('button',{name:'Close',exact:true}).click();
 await focus.waitFor({state:'hidden'});
 for (const route of ['/','/dashboard','/chat','/tasks','/cp','/snippets','/code-review','/analytics','/settings','/sign-in','/sign-up','/onboarding']){
   await page.setViewportSize({width:390,height:844});await page.goto('http://localhost:3000'+route,{waitUntil:'networkidle'});
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,route+' overflow');
 }
 await page.goto('http://localhost:3000/dashboard',{waitUntil:'networkidle'});
 assert.equal(await page.getByRole('button',{name:'Open menu',exact:true}).isVisible(),true);
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.getByRole('dialog',{name:'Workspace navigation'}).waitFor();
 await page.getByRole('button',{name:'Close menu',exact:true}).click();
 await page.getByRole('dialog',{name:'Workspace navigation'}).waitFor({state:'hidden'});
 await page.setViewportSize({width:1440,height:1000});
 assert.equal(await page.getByRole('button',{name:'Open menu',exact:true}).isVisible(),false);
 const primary=page.getByRole('button',{name:'Generate plan',exact:true});
 assert.equal(await primary.evaluate(e=>getComputedStyle(e).display),'flex');
 assert.equal(await primary.evaluate(e=>getComputedStyle(e).height),'40px');
 assert.equal(await primary.evaluate(e=>getComputedStyle(e).borderTopStyle),'solid');
 assert.notEqual(await page.getByRole('button',{name:'Start focus',exact:true}).evaluate(e=>getComputedStyle(e).backgroundImage),'none');
 const light=await page.evaluate(()=>getComputedStyle(document.body).backgroundColor);
 await page.getByRole('button',{name:'Toggle theme',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.classList.contains('dark')),true);
 assert.notEqual(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor),light);
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.evaluate(()=>document.documentElement.classList.contains('dark')),true);
 assert.deepEqual(errors,[]);console.log('PASS: history refresh/select, planning repeatability, focus start/pause/save, 12 mobile routes, responsive styles and persisted dark theme; no browser errors.');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
